export interface ThemeStyle {
  id: string;
  name: string;
  tagline: string;
  primary: string; // Brand / ink color
  accent: string;  // Main action / highlight color
  accentSoft: string; // Soft container / tag color
  background: string; // Page background
  cardBg: string; // Card background
  text: string;
  subText: string;
  border: string;

  // Structural & Aesthetic Tokens
  borderRadius: number; // e.g., 0 for brutalist, 12 for standard, 24 for ultra-rounded
  borderWidth: number;  // 1, 2, or 3
  borderStyle?: "solid" | "dashed";
  cardShadow: boolean;
  shadowColor?: string;
  tagRadius: number;
  badgeStyle: "pill" | "square" | "soft";
  fontDesign: "serif" | "sans" | "mono";
}

